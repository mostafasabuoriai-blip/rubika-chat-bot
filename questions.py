# برای سازگاری
PERSONAL_POOL = [
    q for questions in PERSONAL_POOLS.values() for q in questions
]


def get_personal_questions(count=10):
    """۱۰ سوال متوازن — از هر حوزه حداقل یکی"""
    if count <= 0:
        return []

    categories = list(PERSONAL_POOLS.values())
    random.shuffle(categories)

    selected = []
    remaining = []

    for questions in categories:
        shuffled = questions.copy()
        random.shuffle(shuffled)
        selected.append(shuffled.pop())
        remaining.extend(shuffled)

    if count < len(selected):
        selected = random.sample(selected, count)
    elif count > len(selected):
        extra = min(count - len(selected), len(remaining))
        selected.extend(random.sample(remaining, extra))

    random.shuffle(selected)

    # ✅ شماره‌گذاری خودکار
    fa_digits = "۰۱۲۳۴۵۶۷۸۹"
    numbered = []
    for i, q in enumerate(selected[:count], 1):
        num = "".join(fa_digits[int(d)] for d in str(i))
        numbered.append(f"{num}. {q}")

    return numbered


